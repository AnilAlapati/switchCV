/**
 * Retrieves a resume by ID (handling legacy vs numeric IDs).
 * Optionally checks access permissions for a specific user.
 */
export async function getResume(
  id: string,
  userId?: string
): Promise<{
  resume: PublishedResume | null;
  access: "owner" | "admin" | "granted" | "public_snapshot" | "none";
}> {
  const doc = await adminDb.collection("resumes").doc(id).get();

  // If not found, it might be a slug or legacy ID - for now assume direct ID lookup primarily
  if (!doc.exists) {
    // Try numeric ID lookup if string was passed
    // (Existing logic in some places assumes ID is a string but might be stored as numeric string)
    return { resume: null, access: "none" };
  }

  const data = doc.data();
  if (!data) return { resume: null, access: "none" };

  // Cast to PublishedResume - document existence is verified above
  const resume = data as PublishedResume;

  // 1. Owner Access
  if (userId && resume.userId === userId) {
    return { resume, access: "owner" };
  }

  // 2. Admin Access
  if (userId) {
    const userDoc = await adminDb.collection("users").doc(userId).get();
    if (userDoc.exists && userDoc.data()?.role === "admin") {
      return { resume, access: "admin" };
    }
  }

  // 3. Explicit Access Grant
  if (userId) {
    const accessGranted = await checkPrivateResumeAccess(id, userId);
    if (accessGranted) {
      // Track view
      // Access tracking logic (async)
      return { resume, access: "granted" };
    }
  }

  // 4. Public Access
  if (
    data.isPublic ||
    data.visibility === "public" ||
    data.published === true
  ) {
    const { sanitizeResumeForPublicView } = await import(
      "@/lib/utils/resumeVisibility"
    );
    const sanitized = sanitizeResumeForPublicView(data);
    return {
      resume: {
        ...sanitized,
        isBeingEdited: resume.isBeingEdited,
      } as PublishedResume,
      access: "public_snapshot",
    };
  }

  return { resume: null, access: "none" };
}

/**
 * Checks for granular access grants (e.g. recruiters).
 */
export async function checkPrivateResumeAccess(
  resumeId: string,
  viewerId: string
): Promise<boolean> {
  try {
    const resumeRef = adminDb.collection("resumes").doc(resumeId);
    const grantsSnap = await resumeRef
      .collection("accessGrants")
      .where("toUserId", "==", viewerId)
      .get();

    if (grantsSnap.empty) return false;

    const now = new Date();
    return grantsSnap.docs.some((doc) => {
      const data = doc.data();
      if (data.toUserId !== viewerId) return false;

      // Handle Timestamp or Date string
      let expiresAt: Date | null = null;
      if (data.expiresAt?.toDate) expiresAt = data.expiresAt.toDate();
      else if (data.expiresAt) expiresAt = new Date(data.expiresAt);

      return !expiresAt || expiresAt > now;
    });
  } catch (error) {
    logger.error(
      { err: error, resumeId, viewerId },
      "Error checking access grant"
    );
    return false;
  }
}

/**
 * Updates a resume with new data.
 */
export async function updateResume(
  id: string,
  userId: string,
  data: Partial<ResumeProfile>
): Promise<void> {
  const { sanitizeResumePayload } = await import("@/lib/utils/resumeEditor");
  const sanitized = sanitizeResumePayload(data);
  const timestamp = new Date().toISOString();

  await adminDb
    .collection("resumes")
    .doc(id)
    .set(
      {
        ...sanitized,
        updatedAt: timestamp,
        lastUpdatedAt: timestamp,
      },
      { merge: true }
    );
}

/**
 * Deletes a resume and recycles its ID.
 */
export async function deleteResume(id: string, userId: string): Promise<void> {
  const { addDeletedIdToPool } = await import("@/lib/resumeIdRecycler");

  // Safety check - though controller should handle ownership
  const docRef = adminDb.collection("resumes").doc(id);
  const doc = await docRef.get();

  if (!doc.exists) throw new Error("Resume not found");
  if (doc.data()?.userId !== userId) throw new Error("Unauthorized");

  // Use recursive delete to handle subcollections (accessRequests, accessGrants)
  await adminDb.recursiveDelete(docRef);

  // Also delete the denormalized reference in user's collection
  try {
    await adminDb
      .collection("users")
      .doc(userId)
      .collection("userResumes")
      .doc(id)
      .delete();
  } catch (error) {
    logger.warn(
      { err: error, userId, resumeId: id },
      "Failed to delete userResume reference"
    );
  }

  // Recycle ID
  const numericId = parseInt(id, 10);
  if (!isNaN(numericId)) {
    addDeletedIdToPool(numericId).catch((err) =>
      logger.error({ err, numericId }, "Failed to recycle resume ID in service")
    );
  }
}

/**
 * Generates and saves vector embedding for a resume.
 * This effectively updates the "searchProfile" which is the text representation.
 */
export async function updateResumeEmbedding(
  resumeId: string,
  data: PublishedResume
): Promise<void> {
  const { generateEmbedding } = await import(
    "@/lib/services/aiGenerationService"
  );

  // Construct text representation
  const profile = data.profile;
  const parts = [
    profile.title,
    profile.summary,
    ...profile.experience.map(
      (e) => `${e.role} at ${e.company}: ${e.description}`
    ),
    ...profile.skills.map((s) => s.name),
    ...profile.projects.map((p) => `${p.name}: ${p.description}`),
  ].filter(Boolean);

  const searchText = parts.join("\n\n");

  if (!searchText.trim()) return;

  try {
    const embedding = await generateEmbedding(searchText);

    await adminDb.collection("resumes").doc(resumeId).update({
      embedding,
      embeddingUpdatedAt: new Date().toISOString(),
      searchProfile: searchText,
    });

    logger.info({ resumeId }, "Vector embedding updated");
  } catch (error) {
    logger.error({ err: error, resumeId }, "Failed to update embedding");
  }
}
