/**
 * Publishes a draft resume, making it searchable by recruiters.
 *
 * For new resumes: Assigns a numeric ID and creates in resumes collection.
 * For edited resumes: Updates the existing resume with new content.
 *
 * This operation is atomic - either everything succeeds or nothing changes.
 *
 * @param draftId - The draft ID to publish
 * @param userId - The user ID (for ownership verification)
 * @returns The published resume with its numeric ID
 * @throws Error if draft not found or not owned by user
 */
export async function publishDraft(
  draftId: string,
  userId: string
): Promise<PublishedResume> {
  // Get the draft (verifies ownership)
  const draft = await getDraft(draftId, userId);

  if (!draft) {
    throw new Error(`Draft not found or access denied: ${draftId}`);
  }

  const now = new Date().toISOString();
  const batch = adminDb.batch();

  let resumeId: number;
  let isNewResume = false;

  // Determine if this is a new resume or republishing an edited one
  if (draft.resumeId === null) {
    // New resume - assign a numeric ID
    resumeId = await getNextResumeId();
    isNewResume = true;
  } else {
    // Republishing - use the existing ID
    resumeId = draft.resumeId;
  }

  const publishedResume: PublishedResume = {
    resumeId,
    userId,
    profile: draft.profile,
    publishedAt: isNewResume
      ? now
      : (await getExistingPublishedAt(resumeId)) || now,
    updatedAt: now,
    isBeingEdited: false,
    // embedding will be generated by Cloud Function trigger
  };

  // Write to resumes collection
  batch.set(
    adminDb.collection("resumes").doc(resumeId.toString()),
    publishedResume
  );

  // Create ID mapping for new resumes
  if (isNewResume) {
    batch.set(adminDb.collection("resumeIdMapping").doc(resumeId.toString()), {
      documentId: resumeId.toString(),
      userId,
      resumeId,
      createdAt: now,
    });
  }

  // Delete the draft
  batch.delete(adminDb.collection(DRAFT_CONFIG.COLLECTION).doc(draftId));

  // Release the draft ID mapping
  batch.delete(
    adminDb.collection(DRAFT_CONFIG.ID_MAPPING_COLLECTION).doc(draftId)
  );

  // Execute atomically with error recovery
  try {
    await batch.commit();
  } catch (error) {
    // Log the error for debugging
    logger.error(
      { err: error, resumeId, draftId, userId },
      "Batch commit failed during publish"
    );

    // Attempt to clean up partial state if possible
    // Note: In production, consider using a saga pattern or two-phase commit
    // for more robust error recovery
    throw new Error(
      `Failed to publish draft: ${
        error instanceof Error ? error.message : "Unknown error"
      }. Please try again.`
    );
  }

  logger.info(
    { resumeId, draftId, userId, isNewResume },
    "Draft published successfully"
  );

  return publishedResume;
}

/**
 * Gets the original publishedAt timestamp for an existing resume.
 * Used to preserve the original publish date when republishing.
 */
async function getExistingPublishedAt(
  resumeId: number
): Promise<string | null> {
  const doc = await adminDb
    .collection("resumes")
    .doc(resumeId.toString())
    .get();
  if (!doc.exists) {
    return null;
  }
  return doc.data()?.publishedAt || null;
}

/**
 * Unpublishes a resume for editing.
 *
 * Creates a new draft from the published resume content and marks
 * the published resume as "being edited". The public URL will show
 * a "Resume is being edited" message instead of 404.
 *
 * @param resumeId - The numeric resume ID to unpublish
 * @param userId - The user ID (for ownership verification)
 * @returns The new draft created for editing
 * @throws Error if resume not found or not owned by user
 */
export async function unpublishResume(
  resumeId: number,
  userId: string
): Promise<DraftResume> {
  // Get the published resume
  const resumeDoc = await adminDb
    .collection("resumes")
    .doc(resumeId.toString())
    .get();

  if (!resumeDoc.exists) {
    throw new Error(`Resume not found: ${resumeId}`);
  }

  const publishedResume = resumeDoc.data() as PublishedResume;

  // Verify ownership
  if (publishedResume.userId !== userId) {
    throw new Error(`Access denied to resume: ${resumeId}`);
  }

  // Check if already being edited
  if (publishedResume.isBeingEdited) {
    throw new Error(
      `Resume ${resumeId} is already being edited. ` +
        `Draft ID: ${publishedResume.editingDraftId}`
    );
  }

  // Import here to avoid circular dependency
  const { generateUniqueDraftId, reserveDraftId } = await import(
    "@/lib/draftIdGenerator"
  );

  // Generate new draft ID
  const draftId = await generateUniqueDraftId();
  await reserveDraftId(draftId, userId, resumeId);

  const now = new Date().toISOString();

  const draft: DraftResume = {
    draftId,
    userId,
    resumeId, // Link to the original published resume
    profile: publishedResume.profile,
    createdAt: now,
    updatedAt: now,
  };

  const batch = adminDb.batch();

  // Create the draft
  batch.set(adminDb.collection(DRAFT_CONFIG.COLLECTION).doc(draftId), draft);

  // Mark the published resume as being edited
  batch.update(adminDb.collection("resumes").doc(resumeId.toString()), {
    isBeingEdited: true,
    editingDraftId: draftId,
    updatedAt: now,
  });

  // Execute atomically with error recovery
  try {
    await batch.commit();
  } catch (error) {
    // Log the error for debugging
    logger.error(
      { err: error, resumeId, draftId, userId },
      "Batch commit failed during unpublish"
    );

    // Clean up the draft ID mapping if the batch failed
    // This prevents orphaned ID reservations
    try {
      await adminDb
        .collection(DRAFT_CONFIG.ID_MAPPING_COLLECTION)
        .doc(draftId)
        .delete();
    } catch (cleanupError) {
      logger.warn(
        { err: cleanupError, draftId },
        "Failed to clean up draft ID mapping after batch failure"
      );
    }

    throw new Error(
      `Failed to unpublish resume: ${
        error instanceof Error ? error.message : "Unknown error"
      }. Please try again.`
    );
  }

  logger.info({ resumeId, draftId, userId }, "Resume unpublished for editing");

  return draft;
}

/**
 * Gets a published resume by its numeric ID.
 * Returns metadata about editing state for proper UI display.
 *
 * @param resumeId - The numeric resume ID
 * @returns The published resume or null if not found
 */
export async function getPublishedResume(
  resumeId: number
): Promise<PublishedResume | null> {
  const doc = await adminDb
    .collection("resumes")
    .doc(resumeId.toString())
    .get();

  if (!doc.exists) {
    return null;
  }

  return doc.data() as PublishedResume;
}

/**
 * Checks if a resume is currently being edited.
 * Used by the public resume page to show appropriate message.
 *
 * @param resumeId - The numeric resume ID
 * @returns Object with editing status
 */
export async function getResumeEditingStatus(
  resumeId: number
): Promise<{ exists: boolean; isBeingEdited: boolean }> {
  const resume = await getPublishedResume(resumeId);

  if (!resume) {
    return { exists: false, isBeingEdited: false };
  }

  return { exists: true, isBeingEdited: resume.isBeingEdited };
}
