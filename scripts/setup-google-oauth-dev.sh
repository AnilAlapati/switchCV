#!/bin/bash

echo "========================================"
echo "🔐 Google OAuth Setup for switchcv-dev"
echo "========================================"
echo ""
echo "I'll open the required pages for you. Follow the steps below:"
echo ""

# Step 1
echo "📋 STEP 1: Configure OAuth Consent Screen"
echo "-------------------------------------------"
echo "Opening Google Cloud Console OAuth Consent Screen..."
sleep 2
open "https://console.cloud.google.com/apis/credentials/consent?project=switchcv-dev"
echo ""
echo "✅ Do this:"
echo "   1. If asked, choose 'External' user type, click CREATE"
echo "   2. Fill in:"
echo "      - App name: SwitchCV"
echo "      - User support email: (select your email)"
echo "      - Authorized domains: Add 'switchcv-dev.firebaseapp.com'"
echo "      - Developer contact: (your email)"
echo "   3. Click 'SAVE AND CONTINUE' (3 times - skip Scopes and Test users)"
echo "   4. Click 'BACK TO DASHBOARD'"
echo ""
read -p "Press ENTER when you've completed Step 1..."

# Step 2
echo ""
echo "📋 STEP 2: Create OAuth Client ID"
echo "-------------------------------------------"
echo "Opening Credentials page..."
sleep 2
open "https://console.cloud.google.com/apis/credentials?project=switchcv-dev"
echo ""
echo "✅ Do this:"
echo "   1. Click '+ CREATE CREDENTIALS' at the top"
echo "   2. Select 'OAuth client ID'"
echo "   3. Application type: Web application"
echo "   4. Name: SwitchCV Web Client"
echo "   5. Authorized JavaScript origins - Add these 3 URLs:"
echo "      http://localhost:3000"
echo "      https://switchcv-dev.firebaseapp.com"
echo "      https://switchcv-dev.web.app"
echo ""
echo "   6. Authorized redirect URIs - Add these 3 URLs:"
echo "      http://localhost:3000/__/auth/handler"
echo "      https://switchcv-dev.firebaseapp.com/__/auth/handler"
echo "      https://switchcv-dev.web.app/__/auth/handler"
echo ""
echo "   7. Click CREATE"
echo "   8. A popup will show your Client ID and Client Secret"
echo "      IMPORTANT: Keep this popup open or copy both values!"
echo ""
read -p "Press ENTER when you've created the OAuth client..."

# Step 3
echo ""
echo "📋 STEP 3: Add Credentials to Firebase"
echo "-------------------------------------------"
echo "Opening Firebase Console..."
sleep 2
open "https://console.firebase.google.com/project/switchcv-dev/authentication/providers"
echo ""
echo "✅ Do this:"
echo "   1. Click on the 'Google' row"
echo "   2. Paste your Client ID into 'Web client ID'"
echo "   3. Paste your Client Secret into 'Web client secret'"
echo "   4. Click SAVE"
echo ""
read -p "Press ENTER when you've saved to Firebase..."

# Step 4
echo ""
echo "📋 STEP 4: Test the Setup"
echo "-------------------------------------------"
echo "Starting dev server..."
npm run dev &
SERVER_PID=$!
sleep 5
echo ""
echo "Opening auth page..."
open "http://localhost:3000/auth"
echo ""
echo "✅ Do this:"
echo "   1. Click the '🔍 Debug' button (bottom-right corner)"
echo "   2. Click '🧪 Test Google Sign-In'"
echo "   3. Complete the Google sign-in flow"
echo ""
echo "Expected result: '✅ SUCCESS! User: [your-email]'"
echo ""
read -p "Press ENTER when you've tested..."

echo ""
echo "========================================"
echo "✅ Setup Complete!"
echo "========================================"
echo ""
echo "If it worked: You're all set! Google Sign-In is now configured."
echo "If it failed: Check the error message in the debug panel."
echo ""
echo "To stop the dev server: kill $SERVER_PID"
